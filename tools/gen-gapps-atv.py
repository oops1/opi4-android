#!/usr/bin/env python3
"""Turn a MindTheGapps ATV flashable zip into an in-tree vendor/gapps-atv (like vendor/gapps).

Usage: gen-gapps-atv.py MindTheGapps-16.0.0-arm64-ATV-full-*.zip [aosp_top]

Creates <aosp_top>/vendor/gapps-atv with:
  proprietary/{system,system_ext,product}/...  files from the zip
  Android.bp           soong_namespace + android_app_import / prebuilt_overlay modules
  gapps-atv-vendor.mk  PRODUCT_SOONG_NAMESPACES, PRODUCT_PACKAGES, PRODUCT_COPY_FILES
The APKs are Google's and not redistributable: vendor/gapps-atv never goes into the port repo.
"""
import os
import shutil
import sys
import zipfile

zpath = sys.argv[1]
top = sys.argv[2] if len(sys.argv) > 2 else os.path.expanduser("~/aosp")
dst = os.path.join(top, "vendor/gapps-atv")
prop = os.path.join(dst, "proprietary")
if os.path.isdir(dst):
    shutil.rmtree(dst)
os.makedirs(prop)

PART_OUT = {"system": "$(TARGET_COPY_OUT_SYSTEM)", "system_ext": "$(TARGET_COPY_OUT_SYSTEM_EXT)",
            "product": "$(TARGET_COPY_OUT_PRODUCT)"}
SPECIFIC = {"system": None, "system_ext": "system_ext_specific", "product": "product_specific"}

apps, overlays, copies = [], [], []
with zipfile.ZipFile(zpath) as z:
    for name in z.namelist():
        # zip layout: system/<partition>/<path>; system/system/... is the system partition
        if not name.startswith("system/") or name.endswith("/") or "/addon.d/" in name:
            continue
        rest = name[len("system/"):]
        part, sub = rest.split("/", 1)
        if part not in PART_OUT:
            continue
        out = os.path.join(prop, part, sub)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with z.open(name) as src, open(out, "wb") as f:
            shutil.copyfileobj(src, f)
        rel = f"proprietary/{part}/{sub}"
        if sub.endswith(".apk") and sub.startswith("overlay/"):
            overlays.append((os.path.splitext(os.path.basename(sub))[0], part, rel))
        elif sub.endswith(".apk"):
            kind = sub.split("/")[0]                     # app | priv-app
            apps.append((os.path.splitext(os.path.basename(sub))[0], part, rel, kind == "priv-app"))
        else:
            copies.append((rel, f"{PART_OUT[part]}/{sub}"))

bp = ["// Generated by opi4-android tools/gen-gapps-atv.py from " + os.path.basename(zpath), "",
      "soong_namespace {", "}", ""]
for name, part, rel, priv in sorted(apps):
    bp += ["android_app_import {", f'    name: "{name}",', '    owner: "gapps",', f'    apk: "{rel}",',
           "    preprocessed: true,", "    presigned: true,", "    dex_preopt: {", "        enabled: false,",
           "    },"]
    if priv:
        bp.append("    privileged: true,")
    if SPECIFIC[part]:
        bp.append(f"    {SPECIFIC[part]}: true,")
    bp += ["}", ""]
for name, part, rel in sorted(overlays):
    bp += ["prebuilt_overlay {", f'    name: "{name}",', f'    src: "{rel}",',
           f'    filename: "{name}.apk",']
    if SPECIFIC[part]:
        bp.append(f"    {SPECIFIC[part]}: true,")
    bp += ["}", ""]
open(os.path.join(dst, "Android.bp"), "w").write("\n".join(bp))

mk = ["# Generated by opi4-android tools/gen-gapps-atv.py", "",
      "PRODUCT_SOONG_NAMESPACES += vendor/gapps-atv", "", "PRODUCT_PACKAGES += \\"]
mk += [f"    {n} \\" for n in sorted([a[0] for a in apps] + [o[0] for o in overlays])]
mk += ["", "PRODUCT_COPY_FILES += \\"]
mk += [f"    vendor/gapps-atv/{src}:{d} \\" for src, d in sorted(copies)]
mk += [""]          # ro.com.google.gmsversion comes from the zip's etc/init/gapps.rc
open(os.path.join(dst, "gapps-atv-vendor.mk"), "w").write("\n".join(mk))
print(f"{dst}: {len(apps)} apps, {len(overlays)} overlays, {len(copies)} files")
