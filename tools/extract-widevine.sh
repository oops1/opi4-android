#!/bin/bash
# Pull Google's Widevine L3 DRM HAL (a self-contained vendor APEX) out of the official
# Android 16 emulator image with Google Play, into ~/aosp/vendor/widevine for opi4_tv.
#
#   tools/extract-widevine.sh /mnt/f/OrangePi4/app/arm64-v8a-36_r07.zip
#
# Image: https://dl.google.com/android/repository/sys-img/google_apis_playstore/arm64-v8a-36_r07.zip
# The emulator has no TEE, so its Widevine is the software (L3) one, which is what this board
# can run. The APEX only needs LLNDK libraries (liblog, libbinder_ndk, libc), brings its own
# init rc and VINTF fragment. It is Google's, proprietary and not redistributable:
# vendor/widevine stays out of the port repo, and builds meant to be shared must not use it.
set -e
ZIP=${1:?emulator system image zip}
TOP=${AOSP:-$HOME/aosp}
HOST=$TOP/out/host/linux-x86/bin
DST=$TOP/vendor/widevine
W=$(mktemp -d)
trap 'rm -rf $W' EXIT
cd $W

echo "== vendor.img from $(basename $ZIP)"
unzip -q -o "$ZIP" '*/vendor.img' -d $W
IMG=$(find $W -name vendor.img | head -1)
# The emulator ships vendor.img as a GPT disk with one "vendor" partition
START=$(/sbin/sfdisk -d "$IMG" 2>/dev/null | sed -n 's/.*start= *\([0-9]*\),.*name="vendor".*/\1/p')
if [ -n "$START" ]; then
    SIZE=$(/sbin/sfdisk -d "$IMG" | sed -n 's/.*size= *\([0-9]*\),.*name="vendor".*/\1/p')
    dd if="$IMG" of=$W/vendor.fs bs=512 skip=$START count=$SIZE status=none
else
    cp "$IMG" $W/vendor.fs
fi
file vendor.fs | grep -qi "android sparse" && $HOST/simg2img vendor.fs vendor.raw && mv vendor.raw vendor.fs

mkdir -p v
($HOST/fsck.erofs --extract=v vendor.fs >/dev/null 2>&1) || debugfs -R "rdump / v" vendor.fs >/dev/null 2>&1
APEX=$(ls v/apex/com.google.android.widevine*.apex 2>/dev/null | head -1)
[ -n "$APEX" ] || { echo "no com.google.android.widevine APEX in vendor"; exit 1; }
echo "   $(basename $APEX) ($(du -h $APEX | cut -f1))"

rm -rf $DST && mkdir -p $DST
cp $APEX $DST/com.google.android.widevine.apex
cat > $DST/widevine-vendor.mk <<'EOT'
# Generated by opi4-android tools/extract-widevine.sh
PRODUCT_COPY_FILES += \
    vendor/widevine/com.google.android.widevine.apex:$(TARGET_COPY_OUT_VENDOR)/apex/com.google.android.widevine.apex
EOT
echo "== $DST ready"
