#!/bin/bash
# Pull Google's Widevine L3 DRM HAL out of an official Android Emulator system image
# (Android 16, arm64, "Google Play" flavour) into ~/aosp/vendor/widevine for the opi4_tv build.
#
#   tools/extract-widevine.sh /mnt/f/OrangePi4/app/arm64-v8a-36_r07.zip
#
# Image: https://dl.google.com/android/repository/sys-img/google_apis_playstore/arm64-v8a-36_r07.zip
# The emulator has no TEE, so its Widevine is the software (L3) one, which is what this board
# can run. The files are Google's, proprietary and not redistributable: vendor/widevine stays
# out of the port repo, and builds meant to be shared must not include it.
set -e
ZIP=${1:?emulator system image zip}
TOP=${AOSP:-$HOME/aosp}
HOST=$TOP/out/host/linux-x86/bin
DST=$TOP/vendor/widevine
W=$(mktemp -d)
trap 'rm -rf $W' EXIT

echo "== unpacking vendor image from $(basename $ZIP)"
unzip -q -o "$ZIP" '*/vendor.img' -d $W 2>/dev/null || unzip -q -o "$ZIP" 'vendor.img' -d $W
IMG=$(find $W -name vendor.img | head -1)
[ -n "$IMG" ] || { echo "no vendor.img in the zip"; exit 1; }
if file "$IMG" | grep -qi "android sparse"; then $HOST/simg2img "$IMG" $W/vendor.raw; IMG=$W/vendor.raw; fi

echo "== extracting files ($(file -b "$IMG" | cut -c1-40))"
mkdir -p $W/v
if file "$IMG" | grep -qi erofs || $HOST/dump.erofs "$IMG" >/dev/null 2>&1; then
    $HOST/fsck.erofs --extract=$W/v "$IMG" >/dev/null
else
    debugfs -R "rdump / $W/v" "$IMG" >/dev/null 2>&1
fi

cd $W/v
FILES=$(find . -iname '*widevine*' -o -name 'libwv*.so' -o -name 'liboemcrypto*.so' | sed 's#^\./##' | sort)
[ -n "$FILES" ] || { echo "no Widevine files found in vendor"; exit 1; }
echo "$FILES" | sed 's/^/   /'

# Shared libraries the Widevine binaries need that our vendor image may not have
NEED=$(for f in $(echo "$FILES" | grep -E '(bin/hw/|\.so$)'); do readelf -d $f 2>/dev/null | sed -n 's/.*Shared library: \[\(.*\)\]/\1/p'; done | sort -u)
EXTRA=""
for l in $NEED; do
    if [ ! -e $TOP/out/target/product/opi4/vendor/lib64/$l ] && [ ! -e $TOP/out/target/product/opi4/system/lib64/$l ] \
       && [ -e lib64/$l ] && ! echo "$FILES" | grep -q "lib64/$l"; then EXTRA="$EXTRA lib64/$l"; fi
done
[ -n "$EXTRA" ] && echo "   + needed vendor libs:$EXTRA"

rm -rf $DST && mkdir -p $DST/proprietary
for f in $FILES $EXTRA; do mkdir -p $DST/proprietary/$(dirname $f); cp -a $f $DST/proprietary/$f; done

SVC=$(echo "$FILES" | grep '^bin/hw/' | head -1)
{
    echo "# Generated by opi4-android tools/extract-widevine.sh from $(basename $ZIP)"
    echo "PRODUCT_COPY_FILES += \\"
    for f in $FILES $EXTRA; do
        case $f in etc/init/*) continue ;; esac    # replaced by widevine.rc below (own seclabel)
        echo "    vendor/widevine/proprietary/$f:\$(TARGET_COPY_OUT_VENDOR)/$f \\"
    done
    echo "    vendor/widevine/widevine.rc:\$(TARGET_COPY_OUT_VENDOR)/etc/init/widevine.opi4.rc"
} > $DST/widevine-vendor.mk

# The emulator's rc relies on its own SELinux domain; run the HAL in AOSP's hal_drm_default
cat > $DST/widevine.rc <<EOT
service vendor.drm-widevine /vendor/$SVC
    class hal
    user media
    group media mediadrm drmrpc
    ioprio rt 4
    task_profiles ProcessCapacityHigh
    seclabel u:r:hal_drm_default:s0
    interface aidl android.hardware.drm.IDrmFactory/widevine
EOT
echo "== $DST ready: $(du -sh $DST | cut -f1)"
